export function getLocationBySlug(slug) {
  return locations.find((location) => location.slug === slug);
}

export function getSegmentsWithCoordinates() {
  return routeSegments.map((segment) => {
    const fromLocation = getLocationBySlug(segment.from);
    const toLocation = getLocationBySlug(segment.to);
    return {
      ...segment,
      coordinates: [fromLocation.coordinates, toLocation.coordinates],
    };
  });
}
